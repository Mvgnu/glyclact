#!/usr/bin/env python3
"""Join the D-guild trait screen to the virulence screen and rank the usable bench.

Neither screen decides anything on its own. screen_d_guild.py says whether a strain can
make optically pure D-lactate from glycerol; virulence_screen.py says whether it is a
strain you would be allowed to grow. This puts them side by side so the trade-off is
visible per strain instead of being averaged into a score.

Selection is deliberately left out. Which strains go into a pool, and how many, depends
on how the fermentation is run -- whether dld is knocked out or simply starved of oxygen,
whether 1,3-PDO competition is acceptable, how many members the experiment can carry.

Writes results/d_guild/D_GUILD_BENCH.tsv.
"""

from __future__ import annotations

import argparse
import csv
from collections import Counter
from pathlib import Path

TIER_ORDER = {"background": 0, "elevated": 1, "review_required": 2}

SOURCE_ROOT = (
    "/Volumes/T7 Shield/STRAIN_LIBRARY_SEQ_PROCCSSED_DATA/assmebled_and_proccessed_genomes"
)


def read(path: Path) -> list[dict[str, str]]:
    with path.open() as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def role_of(row: dict[str, str]) -> str:
    """Roles name the competing product, because that is the axis that separates members.

    Every strain here is a producer -- the producer/supporter split is what the community
    landscape falsified. What distinguishes them is where their reducing power goes.
    """
    rival = {
        "acids only": "d_producer_clean",
        "1,3-PDO": "d_producer_diverts_pdo",
        "2,3-BD": "d_producer_diverts_bd",
        "1,3-PDO + 2,3-BD": "d_producer_diverts_pdo_bd",
    }.get(row["competing_product"], "d_producer")
    return rival if row["biosafety_tier"] == "background" else f"flagged_{rival}"


def rationale_of(row: dict[str, str]) -> str:
    identity = {
        "clean": f"{row['genus']}, consistent with its family assignment.",
        "genus_uncertain": f"{row['genus']} by MEGAN, but the family row disagrees; needs ANI.",
        "weak": f"{row['genus']} on thin coverage; needs ANI.",
        "no_taxonomy": "No MEGAN taxonomy; identity unresolved pending ANI.",
    }.get(row["taxonomy_flag"], f"{row['genus']}.")
    route = {
        "both": "both the glpK/glpD and gldA/dhaK routes",
        "glpK_respiratory": "glpK/glpD only, so its glycerol electrons enter the quinone pool",
        "gldA_fermentative": "gldA/dhaK only, so its glycerol electrons land on NAD",
    }.get(row["glycerol_route"], row["glycerol_route"])
    parts = [
        identity,
        f"D-LDH x{row['d_ldh_copies']}, no L-LDH, no racemase, ferments pyruvate.",
        f"Takes glycerol by {route}.",
        (f"Carries dld, so it can re-consume D-lactate whenever a terminal acceptor is "
         f"available; knockout target if the run is aerated."
         if row["needs_dld_knockout"] == "yes" else
         "No dld: cannot re-consume D-lactate even under aeration."),
        (f"Diverts reducing power to {row['competing_product']}."
         if row["competing_product"] != "acids only"
         else "No competing reductive product."),
        ("Lactate transporter present." if int(row["exports_lactate"])
         else "No annotated lactate transporter."),
        f"Handles {row['impurities_handled'].replace(',', ', ')} in crude glycerol.",
    ]
    if row["biosafety_tier"] == "background":
        parts.append("Biosafety: nothing decisive on VFDB core or AMRFinderPlus.")
    else:
        parts.append(f"Biosafety {row['biosafety_tier'].replace('_', ' ')}: "
                     f"{row['biosafety_reason']}.")
    return " ".join(parts)


def emit_panel(rows: list[dict[str, str]], path: Path) -> None:
    lines = ["# generated by d_guild_bench.py --emit-panel; edit the screen, not this file",
             f"source_root: {SOURCE_ROOT}", "", "candidates:"]
    for row in rows:
        lines.append(f"  - genome: {row['genome']}")
        lines.append(f"    role: {role_of(row)}")
        lines.append("    rationale: >-")
        words, line = rationale_of(row).split(), "     "
        for word in words:
            if len(line) + len(word) + 1 > 92:
                lines.append(line)
                line = "     "
            line += " " + word
        lines.append(line)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path} with {len(rows)} candidates")


def main() -> None:
    root = Path(__file__).parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--screen", type=Path,
                        default=root / "results" / "d_guild" / "d_guild_screen.tsv")
    parser.add_argument("--virulence", type=Path,
                        default=root / "results" / "d_guild" / "virulence_screen.tsv")
    parser.add_argument("--output", type=Path,
                        default=root / "results" / "d_guild" / "D_GUILD_BENCH.tsv")
    parser.add_argument("--top", type=int, default=30)
    parser.add_argument("--emit-panel", type=Path, nargs="?", const=root / "d_guild_panel.yaml",
                        help="Write a prepare_candidates.py panel for the bench.")
    parser.add_argument("--exclude-flagged", action="store_true",
                        help="Leave strains above the background biosafety tier out of the panel.")
    options = parser.parse_args()

    biosafety = {r["genome"]: r for r in read(options.virulence)}
    rows = []
    for strain in read(options.screen):
        if strain["guild_member"] != "1" or strain["source"] == "reference_assembly":
            continue
        safety = biosafety.get(strain["genome"], {})
        rows.append({
            "genome": strain["genome"],
            "genus": strain["genus"],
            "source": strain["source"],
            "biosafety_tier": safety.get("biosafety_tier", "not screened"),
            "biosafety_reason": safety.get("tier_reasons", "-"),
            "glycerol_route": strain["glycerol_route"],
            "competing_product": strain["competing_product"],
            "reuptake_risk": strain["reuptake_risk"],
            "needs_dld_knockout": "yes" if int(strain["eats_D_lactate"]) else "no",
            "exports_lactate": strain["exports_lactate"],
            "d_ldh_copies": strain["d_ldh_copies"],
            "impurities_handled": strain["impurities_handled"],
            "impurity_breadth": strain["impurity_breadth"],
            "acquired_resistance": safety.get("acquired_resistance_genes", "-"),
            "taxonomy_flag": strain["taxonomy_flag"],
        })

    rows.sort(key=lambda r: (
        TIER_ORDER.get(r["biosafety_tier"], 3),
        r["needs_dld_knockout"] == "yes",
        r["competing_product"] != "acids only",
        -int(r["impurity_breadth"]),
        -int(r["exports_lactate"]),
        r["genome"],
    ))

    options.output.parent.mkdir(parents=True, exist_ok=True)
    with options.output.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)
    print(f"{len(rows)} bench strains -> {options.output}")

    if options.emit_panel:
        panel = [r for r in rows
                 if not (options.exclude_flagged and r["biosafety_tier"] != "background")]
        emit_panel(panel, options.emit_panel)
        if len(panel) < len(rows):
            dropped = [r["genome"] for r in rows if r not in panel]
            print(f"  left out {len(dropped)} flagged: {', '.join(dropped)}")

    clean = [r for r in rows if r["biosafety_tier"] == "background"]
    print(f"\n{len(clean)} carry nothing decisive on virulence or acquired resistance")

    # dld is near-universal in fermentative Enterobacteriaceae, so it separates process
    # regimes rather than strains: it is idle without a terminal acceptor and is a knockout
    # target if the run is aerated. The competing reductive product is the axis that does
    # separate strains, because it diverts the same NADH lactate needs.
    print("\nbiosafety-clean bench, by what competes with lactate for reducing power")
    print(f"{'':<22}{'no dld':>10}{'dld present':>14}")
    for rival in ("acids only", "2,3-BD", "1,3-PDO", "1,3-PDO + 2,3-BD"):
        subset = [r for r in clean if r["competing_product"] == rival]
        if not subset:
            continue
        without = len([r for r in subset if r["needs_dld_knockout"] == "no"])
        print(f"  {rival:<20}{without:>10}{len(subset) - without:>14}")

    focus = [r for r in clean if r["competing_product"] == "acids only"
             and int(r["exports_lactate"])]
    print(f"\n{len(focus)} divert nothing to 1,3-PDO or 2,3-BD and carry a lactate "
          f"transporter")
    for genus, n in Counter(r["genus"] for r in focus).most_common():
        print(f"  {genus:<28}{n:>4}")

    print(f"\n{'genome':<10}{'genus':<18}{'route':<19}{'knockout':<10}{'impurities':<26}")
    for row in focus[: options.top]:
        print(f"{row['genome']:<10}{row['genus'][:17]:<18}{row['glycerol_route']:<19}"
              f"{row['needs_dld_knockout']:<10}{row['impurities_handled'][:25]:<26}")


if __name__ == "__main__":
    main()
